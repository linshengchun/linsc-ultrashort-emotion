import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const reportDir = path.join(process.cwd(), 'data', 'reports');
const files = (await readdir(reportDir)).filter((name) => /^\d{4}-\d{2}-\d{2}\.json$/.test(name)).sort().reverse();
const reports = [];
const markdown = {};

for (const file of files) {
  const report = JSON.parse(await readFile(path.join(reportDir, file), 'utf8'));
  reports.push(report);
  markdown[report.date] = await readFile(path.join(reportDir, `${report.date}.md`), 'utf8');
}

const source = `/* Generated by scripts/build-report-index.mjs. Do not edit manually. */\nimport type { Report } from './report-types';\n\nexport const reports = ${JSON.stringify(reports, null, 2)} as Report[];\n\nexport const reportMarkdown = ${JSON.stringify(markdown, null, 2)} as Record<string, string>;\nexport const reportByDate = new Map(reports.map((report) => [report.date, report]));\nexport const latestReport = reports[0];\n`;
await writeFile(path.join(process.cwd(), 'lib', 'generated-reports.ts'), source, 'utf8');
await writeFile(
  path.join(process.cwd(), 'public', 'reports', 'index.json'),
  `${JSON.stringify(reports.map((report) => ({
    date: report.date,
    displayDate: report.displayDate,
    cycle: report.conclusion.cycle,
    substate: report.conclusion.substate,
    temperature: report.conclusion.temperature,
  })), null, 2)}\n`,
  'utf8',
);
console.log(`Indexed ${reports.length} report(s).`);
